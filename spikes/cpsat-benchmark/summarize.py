"""Summarise results/*.jsonl into results/SUMMARY.md (one row per configuration and scenario)."""

from __future__ import annotations

import glob
import json
import os
import statistics
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "results")
SCENARIOS = ["gen_none", "gen_strict", "rb_target", "rb_rotation", "rb_cap"]
# Batch 1 ran rb_cap with a fixed 10-hour cap that often didn't bind (kept 100%); it was
# redefined to 4 hours below the person's peak week and rerun into *-capfix.jsonl.
OLD_CAP_FILES = {"cpsat-off-2cpu.jsonl", "cpsat-off-4cpu.jsonl", "cpsat-default-4cpu.jsonl"}


def fmt(v, nd=1):
    if v is None:
        return "–"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def progress(rs, key):
    # Only CP-SAT reports intermediate solutions; through PuLP, CBC and HiGHS report once at the end.
    if any(r["solver"] != "cpsat" for r in rs):
        return "n/a"
    return fmt(med([r.get(key) for r in rs]))


def med(vals):
    vals = [v for v in vals if v is not None]
    return statistics.median(vals) if vals else None


def main():
    runs = []
    for path in sorted(glob.glob(os.path.join(RESULTS, "*.jsonl"))):
        name = os.path.basename(path)
        if "smoke" in name or name == "two-options.jsonl":
            continue
        with open(path, encoding="utf-8") as f:
            rows = [json.loads(line) for line in f if line.strip()]
        if name in OLD_CAP_FILES:
            rows = [r for r in rows if r["scenario"] != "rb_cap"]
        runs += rows
    groups = defaultdict(list)
    for r in runs:
        groups[(r["label"], r["scenario"])].append(r)

    lines = [
        "# Benchmark summary",
        "",
        "Generated by `summarize.py` from `results/*.jsonl`. Medians across seeds unless noted; "
        "\"worst\" columns are the worst seed. Gap is in over-coverage slots (one slot = one person "
        "for 15 minutes), so 0 means proven optimal. \"Target met\" counts seeds where student S04 "
        "reached 20 hours in both weeks. It isn't always achievable: each configuration rebalances "
        "from its own generated schedule, and one proven-optimal run (off-3cpu, seed 3) shows the best "
        "possible from that start leaves S04 0.5 hours short. CBC and HiGHS (via PuLP) only report "
        "a final answer, so their progress timings are n/a and they can overrun the time limit.",
        "",
        "| Config | Scenario | Seeds | Status | Wall s | First sol. s | Zero shortfall s | Gap (slots) | "
        "Worst shortfall h | Worst over h | Worst tag-miss h | Min kept % | Target met | Hard violations |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    labels = sorted({k[0] for k in groups})
    for label in labels:
        for sc in SCENARIOS:
            rs = groups.get((label, sc))
            if not rs:
                continue
            statuses = "/".join(sorted({r["status"] for r in rs}))
            tag_miss = max(
                r["check"]["lead_miss_hours"] + r["check"]["cataloguer_miss_hours"] + r["check"]["new_alone_hours"]
                + sum(r["check"]["processor_short_hours"])
                for r in rs
            )
            kept = [r["kept_pct"] for r in rs if r.get("kept_pct") is not None]
            target = [
                all(v == 0 for vals in r["check"].get("target_short_hours", {}).values() for v in vals) for r in rs
            ]
            target_cell = "–" if sc != "rb_target" else f"{sum(target)}/{len(target)}"
            lines.append(
                f"| {label} | {sc} | {len(rs)} | {statuses} | {fmt(med([r['wall_seconds'] for r in rs]))} | "
                f"{progress(rs, 't_first')} | {progress(rs, 't_zero_shortfall')} | "
                f"{fmt(med([r['gap'] for r in rs]), 2)} | {fmt(max(r['check']['shortfall_hours'] for r in rs))} | "
                f"{fmt(max(r['check']['over_hours'] for r in rs))} | {fmt(tag_miss)} | "
                f"{fmt(min(kept) if kept else None)} | {target_cell} | "
                f"{sum(len(r['check']['hard_violations']) for r in rs)} |"
            )
    sizes = [r for r in runs if r["scenario"] == "gen_none"]
    if sizes:
        lines += [
            "",
            "## Model size (gen_none)",
            "",
            "| Config | Candidates | Variables | Constraints | Build s |",
            "|---|---|---|---|---|",
        ]
        seen = set()
        for r in sizes:
            key = (r["label"], r["seed"])
            if key in seen:
                continue
            seen.add(key)
            lines.append(
                f"| {r['label']} seed {r['seed']} | {r['n_candidates']} | {r['n_vars']} | {r['n_constraints']} | "
                f"{r['build_seconds']} |"
            )
    two = os.path.join(RESULTS, "two-options.jsonl")
    if os.path.exists(two):
        with open(two, encoding="utf-8") as f:
            rows = [json.loads(line) for line in f if line.strip()]
        lines += [
            "",
            "## Two rebalance options (SPEC §7.3.1), CP-SAT, 4 CPUs",
            "",
            "From `two_options.py`. Limit = 10% of scheduled hours (stricter than the 30% default, so the "
            "options differ). Hours moved counts a retimed shift in full (conservative). "
            "seq = one after the other, 15 s each on 4 workers; par = at the same time, 30 s each on 2 workers.",
            "",
            "| Seed | Change | Limit h | Option | Status | Wall s | Gap | Moved h | Over h | Target short h |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for r in rows:
            for key, label in (("full_60s", "full, 60 s alone"), ("seq_full", "seq full"),
                               ("seq_limited", "seq limited"), ("par_full", "par full"),
                               ("par_limited", "par limited")):
                v = r[key]
                ts = "; ".join(f"{k} {a}/{b}" for k, (a, b) in v["target_short"].items()) or "–"
                lines.append(f"| {r['seed']} | {r['scenario']} | {r['limit_h']} | {label} | {v['status']} | "
                             f"{v['wall']} | {v['gap']} | {v['moved_h']} | {v['over_h']} | {ts} |")
            lines.append(f"| {r['seed']} | {r['scenario']} | | par wall time (both) | | {r['par_wall']} | | | | |")
    with open(os.path.join(RESULTS, "SUMMARY.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
